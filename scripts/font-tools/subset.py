#!/usr/bin/env python3
"""Manual only. Run against a fresh Jekyll build; see README.md here."""
import argparse, json, copy, hashlib, re
from pathlib import Path
from html.parser import HTMLParser
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

ROOT = Path(__file__).resolve().parents[2]
p = argparse.ArgumentParser()
p.add_argument('site', type=Path)
p.add_argument('--output-root', type=Path, default=ROOT, help='Write candidates outside the repository for comparison')
p.add_argument('--usage', type=Path, required=True, help='Fresh pages.json from audit.cjs on the same content')
p.add_argument('--ascii-core', action='store_true', help='Experimental: strict ASCII partition may change kerning; compare pixels before publishing')
p.add_argument('--restrict-all', action='store_true', help='Experimental: rebases axes and changes rendering; never publish without pixel approval')
p.add_argument('--keep-features', action='store_true')
p.add_argument('--keep-axes', action='store_true', help='Control: retain all original variation data')
a = p.parse_args()
output_root=a.output_root.resolve()
if (a.ascii_core or a.restrict_all) and output_root == ROOT:
    p.error('Experimental variants require --output-root; keep the published defaults unchanged')
for directory in ('css/fonts','_sass','_data','reports/fonts'): (output_root/directory).mkdir(parents=True,exist_ok=True)
usage = json.loads(a.usage.read_text())
assert all('pseudos' in page for page in usage), 'Rerun the current audit.cjs; pseudo-elements must be inspected'
if not any(a.site.rglob('*.html')): p.error('site must contain a fresh Jekyll build')
class Text(HTMLParser):
    def handle_data(self, data): chars.update(map(ord,data))
    def handle_starttag(self, tag, attrs):
        for key,value in attrs:
            if key in ('alt','title','placeholder','value','aria-label') and value: chars.update(map(ord,value))
chars = {0x2010} # Include CSS-generated hyphen, if the source supports it.
for page in sorted(a.site.rglob('*.html')):
    if 'font-fixtures' not in page.parts: Text().feed(page.read_text())
core = set(range(0x20,0x7f)) | {0xa0,0xa9,0xb7,0x2010,0x2013,0x2014,0x2018,0x2019,0x201a,0x201c,0x201d,0x201e,0x2022,0x2026}
# Keep published text in one shaping run; splitting even a currency symbol
# can change fractional glyph positioning. Unused retained Latin stays extended.
if not a.ascii_core: core |= chars
chars |= set(range(0x20,0x180))
fonts=[('Inter','Inter','Inter',300,700),('Mona-Sans','Mona Sans','FI Heading',300,700),('JetBrains-Mono','JetBrains Mono','JetBrains Mono',300,500)]
def ranges(cps):
    groups=[]
    for cp in sorted(cps):
        if groups and cp==groups[-1][1]+1: groups[-1][1]=cp
        else: groups.append([cp,cp])
    return ', '.join(f'U+{lo:04X}'+(f'-{hi:04X}' if hi!=lo else '') for lo,hi in groups)
css=['/* Generated by scripts/font-tools/subset.py; do not edit. */']
report={}
for stem,family,internal,csslow,csshigh in fonts:
    source=ROOT/'css/fonts'/f'{stem}-Variable.woff2'
    original=TTFont(source, recalcTimestamp=False)
    # HarfBuzz renders missing U+2010 using U+002D in the original faces.
    # Make that alias explicit before publishing exact unicode-range coverage.
    for table in original['cmap'].tables:
        if table.isUnicode() and 0x2d in table.cmap and 0x2010 not in table.cmap:
            table.cmap[0x2010]=table.cmap[0x2d]
    selected=set(original.getBestCmap()) & chars
    # Retain source combining-mark coverage alongside the requested Latin repertoire.
    selected |= set(original.getBestCmap()) & set(range(0x300,0x370))
    font=copy.deepcopy(original)
    assert [axis.axisTag for axis in font['fvar'].axes] == ['wght'], 'Audit new axes before subsetting'
    weights=set()
    enabled_features=set()
    for page in usage:
        if '/font-fixtures/' in page['url']: continue
        styles=[json.loads(key) for key in page['runs']] + page.get('pseudos', [])
        for style in styles:
            if style['fontFamily'].split(',')[0].strip(" \"'") != family: continue
            weights.add(float(style['fontWeight']))
            if 'tabular-nums' in style.get('fontVariantNumeric','normal'): enabled_features.add('tnum')
            for tag,value in re.findall(r'[\"\']([A-Za-z0-9]{4})[\"\'](?:\s+(on|off|[0-9]+))?',style.get('fontFeatureSettings','normal')):
                if value not in ('off','0'): enabled_features.add(tag)
            settings=style.get('fontVariationSettings','normal')
            if settings != 'normal':
                overrides=re.findall(r'[\"\']([A-Za-z0-9]{4})[\"\']\s+(-?[0-9.]+)',settings)
                assert overrides and all(tag=='wght' for tag,value in overrides), 'Audit new axis overrides first'
                weights.update(float(value) for tag,value in overrides)
    assert weights, f'No usage found for {family}; audit the same build first'
    axis=font['fvar'].axes[0]
    # Preserve the original axis normalization and IUP delta encoding. The
    # instancer rewrites inferred deltas, which changed large Mono digits by
    # a few pixels. Negative tuples contribute exactly zero at/above default,
    # so discard only those tuples without instancing the remaining outlines.
    # Inter conservatively retains them while a three-pixel underscore
    # discrepancy on the mobile code article remains under investigation.
    limits=(axis.minValue,axis.maxValue)
    removed_tuples=0
    if a.restrict_all and not a.keep_axes:
        limits=(min(weights),max(weights))
        font=instantiateVariableFont(font,{'wght':limits},inplace=True)
    elif not a.keep_axes and stem != 'Inter' and min(weights)>=axis.defaultValue and 'gvar' in font:
        limits=(axis.defaultValue,axis.maxValue)
        for glyph,variations in font['gvar'].variations.items():
            retained=[]
            for variation in variations:
                support=variation.axes.get('wght')
                if support and support[1]<0 and support[2]<=0:
                    removed_tuples+=1
                else:
                    retained.append(variation)
            font['gvar'].variations[glyph]=retained
    # Instancer can omit empty gvar entries; subset expects every glyph key.
    if 'gvar' in font:
        for glyph in font.getGlyphOrder():
            if glyph not in font['gvar'].variations: font['gvar'].variations[glyph]=[]
    report[stem]={'removedUnusedVariationTuples':removed_tuples,'retainedVariationRange':list(limits),'usedWeights':sorted(weights),'enabledCssFeatures':sorted(enabled_features),'sourceBytes':source.stat().st_size,'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'files':{}}
    for part,cps in [('core',selected & core),('extended',selected-core)]:
        f=copy.deepcopy(font)
        options=subset.Options()
        options.hinting=False
        options.notdef_outline=True
        options.glyph_names=True
        options.layout_features=['ccmp','locl','rlig','liga','clig','calt','kern','mark','mkmk'] + sorted(enabled_features)
        if a.keep_features: options.layout_features=['*']
        options.name_IDs=['*'] # retain copyright/license and axis names
        options.name_legacy=True
        options.name_languages=['*']
        # Chrome/macOS needs the capital-X reference in extended files to
        # rasterize upright text identically. It is not advertised in their CSS.
        encoded = cps | ({0x58} if part == 'extended' else set())
        sub=subset.Subsetter(options=options)
        sub.populate(unicodes=encoded)
        sub.subset(f)
        if internal!=family:
            for n in f['name'].names:
                if n.nameID in (1,3,4,6,16,17,21,22,25) or (n.nameID>=256 and ('Mona' in n.toUnicode())):
                    text=n.toUnicode().replace('Mona Sans',internal).replace('MonaSans',internal.replace(' ',''))
                    n.string=text.encode(n.getEncoding())
        # Preserve source global bounds rather than recomputing subset-only metrics.
        f.recalcBBoxes=False
        for key in ('xMin','yMin','xMax','yMax'): setattr(f['head'],key,getattr(font['head'],key))
        f.flavor='woff2';dest=output_root/'css/fonts'/f'{stem}-{part}.woff2';f.save(dest)
        check=TTFont(dest)
        actual=set(check.getBestCmap())
        assert actual == encoded, (stem,part,actual^cps)
        assert not any(t in check for t in ['fpgm','prep','cvt '])
        assert not any(getattr(check['glyf'][g],'program',None) and check['glyf'][g].program.getBytecode() for g in check.getGlyphOrder())
        if not a.restrict_all:
            for weight in sorted(weights):
                source_glyphs=original.getGlyphSet(location={'wght':weight})
                output_glyphs=check.getGlyphSet(location={'wght':weight})
                for glyph in check.getGlyphOrder():
                    before_pen=DecomposingRecordingPen(source_glyphs)
                    after_pen=DecomposingRecordingPen(output_glyphs)
                    source_glyphs[glyph].draw(before_pen)
                    output_glyphs[glyph].draw(after_pen)
                    assert before_pen.value == after_pen.value, (stem,part,weight,glyph,'outline changed')
                    assert source_glyphs[glyph].width == output_glyphs[glyph].width, (stem,part,weight,glyph,'advance changed')
        if internal!=family:
            assert all('Mona' not in n.toUnicode() for n in check['name'].names if n.nameID in (1,3,4,6,16,17,21,22,25))
        digest=hashlib.sha256(dest.read_bytes()).hexdigest()
        asset_url=f'/css/fonts/{dest.name}?v={digest[:16]}'
        css.append(f"@font-face {{\n  font-family: '{family}';\n  src: url('{asset_url}') format('woff2');\n  font-style: normal;\n  font-weight: {csslow} {csshigh};\n  font-display: swap;\n  unicode-range: {ranges(cps)};\n}}")
        report[stem]['files'][part]={'sha256':digest,'url':asset_url,'bytes':dest.stat().st_size,'glyphs':check['maxp'].numGlyphs,'unicodeRange':ranges(cps),'cmapRange':ranges(actual),'axes':{x.axisTag:[x.minValue,x.defaultValue,x.maxValue] for x in check['fvar'].axes} if 'fvar' in check else {},'features':{t:sorted({r.FeatureTag for r in check[t].table.FeatureList.FeatureRecord}) for t in ['GSUB','GPOS'] if t in check and check[t].table.FeatureList}}
(output_root/'_sass/_font-subsets.scss').write_text('\n\n'.join(css)+'\n')
(output_root/'_data/font_preloads.yml').write_text('# Generated by scripts/font-tools/subset.py\n' + ''.join('- ' + report[stem]['files']['core']['url'] + '\n' for stem in ['Mona-Sans','Inter','JetBrains-Mono']))
(output_root/'reports/fonts/after-inventory.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps({k:{p:v['bytes'] for p,v in d['files'].items()} for k,d in report.items()},indent=2))
